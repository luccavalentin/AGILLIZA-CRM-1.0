const LON0 = -74.5;
const LAT0 = 5.6;
const ESCALA = 10;
const COS = Math.cos((14 * Math.PI) / 180);

export function projetar([lon, lat]: Lonlat): [number, number] {
  return [
    Math.round((lon - LON0) * ESCALA * COS * 10) / 10,
    Math.round((LAT0 - lat) * ESCALA * 10) / 10,
  ];
}

/** Largura e altura do desenho (com folga a leste para os rótulos de fora). */
export const LARGURA = Math.ceil(projetar([-30.2, 0])[0]);
export const ALTURA = Math.ceil(projetar([0, -34.2])[1]);

function caminho(pontos: Lonlat[]): string {
  return (
    pontos
      .map((p, i) => {
        const [x, y] = projetar(p);
        return `${i ? "L" : "M"}${x} ${y}`;
      })
      .join("") + "Z"
  );
}

